    ????[0-1][0-9][0-3][0-9]T[0-2][0-9][0-5][0-9][0-5][0-9]Z)
      date -u -d "$(printf '%s' "$1" | sed -E 's/^([0-9]{4})([0-9]{2})([0-9]{2})T([0-9]{2})([0-9]{2})([0-9]{2})Z$/\1-\2-\3T\4:\5:\6Z/')" +%s
      ;;
    ????-??-??T??:??:??Z)
      date -u -d "$1" +%s
      ;;
    *)
      return 1
      ;;
  esac
}
